import {Router} from 'express';
import {query} from '../db.js';
import {escape as e,auth} from '../security.js';
import {form,input} from '../ui.js';
import {generateSecret,validTotp,encryptSecret,decryptSecret} from './mfa-rules.js';
const r=Router(),safe=fn=>(req,res,next)=>Promise.resolve(fn(req,res,next)).catch(next);
const privileged=['super_admin','admin','headteacher','bursar'];
function signedIn(req,res,next){return req.user?next():res.redirect('/login');}
r.get('/mfa',signedIn,safe(async(req,res)=>{
 if(!privileged.includes(req.user.role)&&!privileged.includes(req.user.primary_role))return res.redirect('/dashboard');
 if(req.user.mfa_verified)return res.redirect('/dashboard');
 const user=(await query('SELECT id,mfa_secret_encrypted FROM users WHERE id=$1',[req.user.id])).rows[0];if(!user)return res.sendStatus(404);
 let secret=null;
 if(!user.mfa_secret_encrypted){
  const existing=(await query('SELECT mfa_pending_secret FROM sessions WHERE id=$1',[req.user.session_id])).rows[0];
  if(existing?.mfa_pending_secret)secret=decryptSecret(existing.mfa_pending_secret);
  else{secret=generateSecret();await query('UPDATE sessions SET mfa_pending_secret=$1 WHERE id=$2',[encryptSecret(secret),req.user.session_id]);}
 }
 res.set('Cache-Control','private,no-store');res.locals.render('Secure School Login',`<h1>Two-Step Account Verification</h1>${secret?`<p>Set up an authenticator app. Add a time-based account manually using this secret. This secret must not be shared.</p><div class="card"><strong>Account: ${e(req.user.full_name)}</strong><p><code>${e(secret)}</code></p><p>Type: TOTP, 6 digits, SHA-1, every 30 seconds.</p></div>`:'<p>Enter the 6-digit code generated by your authenticator app.</p>'}<div class="formbox">${form('/mfa',input('Authenticator code','code','text','',true),res.locals.csrf,'Verify and continue')}</div>`);
}));
r.post('/mfa',signedIn,safe(async(req,res)=>{
 if(!privileged.includes(req.user.role)&&!privileged.includes(req.user.primary_role))return res.sendStatus(403);
 const user=(await query('SELECT mfa_secret_encrypted FROM users WHERE id=$1',[req.user.id])).rows[0];
 const pending=(await query('SELECT mfa_pending_secret FROM sessions WHERE id=$1',[req.user.session_id])).rows[0];
 const value=user?.mfa_secret_encrypted||pending?.mfa_pending_secret;if(!value)return res.status(409).send('Reload the verification page to configure MFA.');
 let secret;try{secret=decryptSecret(value);}catch{return res.status(503).send('School MFA encryption is not configured correctly. Contact the system administrator.');}
 if(!validTotp(secret,req.body.code))return res.status(401).send('Invalid verification code. Check your authenticator time and try again.');
 if(!user.mfa_secret_encrypted)await query('UPDATE users SET mfa_secret_encrypted=$1 WHERE id=$2',[value,req.user.id]);
 await query('UPDATE sessions SET mfa_verified=true,mfa_pending_secret=NULL WHERE id=$1',[req.user.session_id]);
 await query('INSERT INTO audit_logs(actor_id,action,entity,entity_id) VALUES($1,$2,$3,$4)',[req.user.id,'mfa_verified','session',req.user.session_id]);res.redirect('/dashboard');
}));
export default r;
